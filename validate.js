// Validates levels.json with the solver, prints stats, writes levels.js
const fs=require('fs');const B=require('./logic.js');
const LV=JSON.parse(fs.readFileSync(__dirname+'/levels.json','utf8'));let bad=0;
LV.forEach((L,i)=>{const S=B.solve(L);const toks=L.grid.join('').match(/../g);
 const okTok=toks.every(t=>/^([EKTAVPCW][UDLR]|##|xx|oo|h\.|t[UDLR]|gg|s\.|\.\.)$/.test(t))&&L.grid.length===L.h&&L.grid.every(r=>r.length===L.w*2);
 if(!S.solvable||!okTok){bad++;console.log('BAD L'+(i+1));}
 console.log(`L${i+1} ch${L.ch} ${L.w}x${L.h} veh ${S.total} startFree ${S.startFree} avgFree ${S.avgFree.toFixed(2)} minFree ${S.minFree} oneChoice ${S.oneChoice}${L.boss?' BOSS':''}`);});
fs.writeFileSync(__dirname+'/levels.js','// generated by validate.js\nconst LEVELS='+JSON.stringify(LV)+';\n');
console.log(bad?bad+' BAD':'ALL '+LV.length+' OK');process.exit(bad?1:0);
